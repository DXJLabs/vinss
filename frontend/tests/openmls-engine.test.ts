import test from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { IDBFactory } from "fake-indexeddb";
import { BrowserOpenMlsBridge } from "../lib/openmls-core/openmls/browser-bridge";
import { IndexedDbOpenMlsCheckpointStore } from "../lib/openmls-core/openmls/indexeddb-checkpoint-store";
import { createOpenMlsWasmLoader } from "../lib/openmls-core/openmls/runtime";
import type { GeneratedOpenMlsWasmModule } from "../lib/openmls-core/openmls/wasm-api";
test("actual OpenMLS WASM: Alice/Bob exchange, persisted reload, tamper rejection and removed member exclusion", async () => {
    const loader = createOpenMlsWasmLoader(async () => await import("../lib/openmls/vinss_mls.js") as unknown as GeneratedOpenMlsWasmModule, { module_or_path: await readFile(new URL("../lib/openmls/vinss_mls_bg.wasm", import.meta.url)) });
    const idb = new IDBFactory();
    const identity = (name: string) => ({ userId: name, installationId: name + "-device", credential: new TextEncoder().encode(name) });
    const member = (name: string) => ({ ...identity(name), role: "admin" as const });
    const store = new IndexedDbOpenMlsCheckpointStore({ dbName: "actual-mls-test", indexedDB: idb, crypto: globalThis.crypto });
    const a = new BrowserOpenMlsBridge(loader, store), b = new BrowserOpenMlsBridge(loader, store), c = new BrowserOpenMlsBridge(loader, store);
    await a.initialize(identity("alice"));
    await b.initialize(identity("bob"));
    await c.initialize(identity("charlie"));
    await a.createGroup({ conversationId: "test-group", title: "test", creator: member("alice") });
    const add = await a.prepareAddMember({ conversationId: "test-group", member: member("bob"), keyPackage: await b.createKeyPackage() });
    await b.joinFromWelcome({ conversationId: "test-group", welcome: add.welcome });
    await a.mergePendingCommit("test-group");
    await a.markGroupStatePublished("test-group");
    const first = await a.encryptApplicationMessage({ conversationId: "test-group", plaintext: new TextEncoder().encode("secret Alice") });
    assert.equal(new TextDecoder().decode((await b.decryptApplicationMessage({ conversationId: "test-group", ciphertext: first.ciphertext })).plaintext), "secret Alice");
    const restored = new BrowserOpenMlsBridge(loader, store);
    await restored.initialize(identity("bob"));
    const second = await a.encryptApplicationMessage({ conversationId: "test-group", plaintext: new TextEncoder().encode("after reload") });
    const corrupted = second.ciphertext.slice();
    corrupted[corrupted.length - 1] = corrupted[corrupted.length - 1]! ^ 1;
    await assert.rejects(restored.decryptApplicationMessage({ conversationId: "test-group", ciphertext: corrupted }));
    assert.equal(new TextDecoder().decode((await restored.decryptApplicationMessage({ conversationId: "test-group", ciphertext: second.ciphertext })).plaintext), "after reload");
    const addCharlie = await a.prepareAddMember({ conversationId: "test-group", member: member("charlie"), keyPackage: await c.createKeyPackage() });
    await restored.processHandshake({ conversationId: "test-group", message: addCharlie.commit });
    await c.joinFromWelcome({ conversationId: "test-group", welcome: addCharlie.welcome });
    await a.mergePendingCommit("test-group");
    await a.markGroupStatePublished("test-group");
    const remove = await a.prepareRemoveMember({ conversationId: "test-group", installationId: "bob-device" });
    await c.processHandshake({ conversationId: "test-group", message: remove.commit });
    await a.mergePendingCommit("test-group");
    await a.markGroupStatePublished("test-group");
    const afterRemoval = await a.encryptApplicationMessage({ conversationId: "test-group", plaintext: new TextEncoder().encode("new epoch") });
    assert.equal(new TextDecoder().decode((await c.decryptApplicationMessage({ conversationId: "test-group", ciphertext: afterRemoval.ciphertext })).plaintext), "new epoch");
    await assert.rejects(restored.decryptApplicationMessage({ conversationId: "test-group", ciphertext: afterRemoval.ciphertext }));
});
test("MLS plaintext inbox is durable with ratchet state and stale controllers cannot overwrite checkpoints", async () => {
    const loader = createOpenMlsWasmLoader(async () => await import("../lib/openmls/vinss_mls.js") as unknown as GeneratedOpenMlsWasmModule, { module_or_path: await readFile(new URL("../lib/openmls/vinss_mls_bg.wasm", import.meta.url)) });
    const store = new IndexedDbOpenMlsCheckpointStore({ dbName: "mls-revision-test", indexedDB: new IDBFactory(), crypto: globalThis.crypto });
    const identity = { userId: "alice", installationId: "alice-device", credential: new Uint8Array([1]) };
    const first = new BrowserOpenMlsBridge(loader, store), stale = new BrowserOpenMlsBridge(loader, store);
    await first.initialize(identity);
    await stale.initialize(identity);
    await first.saveApplicationState(new TextEncoder().encode("durable application state"));
    await assert.rejects(stale.saveApplicationState(new Uint8Array([1])), /checkpoint/);
    await assert.rejects(stale.createKeyPackage(), /initialized/);
    const restored = new BrowserOpenMlsBridge(loader, store);
    await restored.initialize(identity);
    assert.equal(new TextDecoder().decode(restored.readApplicationState()), "durable application state");
});
